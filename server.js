// OpenRouter AI 요청
// ======================================================
//
// ★ 중요
// OpenRouter의 웹 검색 기능을 사용한다.
// 매장명 + 위치를 바탕으로 실제 웹에서
// 매장정보를 확인할 수 있다.
//
// OpenRouter는 현재
// openrouter:web_search
// 서버 도구를 지원한다.
// ======================================================

async function callOpenRouter(messages, options = {}) {

  const {
    useWebSearch = false,
  } = options;


  const requestBody = {
    model:
      "google/gemini-2.5-flash",

    messages,

    temperature: 0.7,

    max_tokens: 10000,
  };


  // ----------------------------------------------------
  // 웹 검색 활성화
  // ----------------------------------------------------

  if (useWebSearch) {

    requestBody.tools = [
      {
        type:
          "openrouter:web_search",
      },
    ];

  }


  const response = await fetch(
    "https://openrouter.ai/api/v1/chat/completions",
    {
      method: "POST",

      headers: {
        "Authorization":
          `Bearer ${OPENROUTER_API_KEY}`,

        "Content-Type":
          "application/json",

        "HTTP-Referer":
          "http://localhost:3000",

        "X-Title":
          "Janmangchacha Blog Writer",
      },

      body:
        JSON.stringify(requestBody),
    }
  );


  const responseText =
    await response.text();


  if (!response.ok) {

    console.error("");
    console.error("OpenRouter 오류:");
    console.error(
      "상태 코드:",
      response.status
    );
    console.error(responseText);
    console.error("");

    throw new Error(
      `AI 요청 실패 (${response.status})`
    );
  }


  let result;

  try {

    result =
      JSON.parse(responseText);

  } catch (error) {

    console.error(
      "AI 응답 JSON 파싱 실패:"
    );

    console.error(
      responseText
    );

    throw new Error(
      "AI 응답을 읽을 수 없습니다."
    );
  }


  const message =
    result?.choices?.[0]?.message;


  let text =
    message?.content;


  // ----------------------------------------------------
  // 일부 모델/응답 형식에서 content가 배열일 경우
  // ----------------------------------------------------

  if (Array.isArray(text)) {

    text =
      text
        .map((item) => {

          if (
            typeof item === "string"
          ) {
            return item;
          }

          return item?.text || "";

        })
        .join("");
  }


  if (!text) {

    console.error(
      "AI 응답에 글이 없습니다:"
    );

    console.error(
      JSON.stringify(
        result,
        null,
        2
      )
    );

    throw new Error(
      "AI가 글을 생성하지 못했습니다."
    );
  }


  return text.trim();
}


