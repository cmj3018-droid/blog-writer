function extractBodyOnly(blogText) {

  let body =
    blogText || "";


  // ----------------------------------------------------
  // 해시태그 제거
  // ----------------------------------------------------

  const hashtagIndex =
    body.indexOf("#");

  if (
    hashtagIndex !== -1
  ) {

    body =
      body.substring(
        0,
        hashtagIndex
      );
  }


  // ----------------------------------------------------
  // 매장정보 이후 제거
  // ----------------------------------------------------

  const storeInfoIndex =
    body.indexOf(
      "📍 매장정보"
    );

  if (
    storeInfoIndex !== -1
  ) {

    body =
      body.substring(
        0,
        storeInfoIndex
      );
  }


  // ----------------------------------------------------
  // 방문 꿀팁 이후 제거
  // ----------------------------------------------------

  const tipIndex =
    body.indexOf(
      "💡 방문 꿀팁"
    );

  if (
    tipIndex !== -1
  ) {

    body =
      body.substring(
        0,
        tipIndex
      );
  }


  // ----------------------------------------------------
  // 제목 제거
  // ----------------------------------------------------

  const lines =
    body.split("\n");


  if (
    lines.length > 1
  ) {

    lines.shift();

    body =
      lines.join("\n");
  }


  return body.trim();
}


