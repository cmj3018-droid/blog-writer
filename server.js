function readRequestBody(req) {
  return new Promise((resolve, reject) => {
    let body = "";

    req.on("data", (chunk) => {
      body += chunk;

      if (body.length > 30 * 1024 * 1024) {
        reject(
          new Error("업로드 용량이 너무 큽니다.")
        );

        req.destroy();
      }
    });

    req.on("end", () => {
      try {
        resolve(JSON.parse(body));
      } catch (error) {
        reject(
          new Error("잘못된 JSON 데이터입니다.")
        );
      }
    });

    req.on("error", reject);
  });
}


